import { test, expect } from '@playwright/test';

test('long-song workspace supports navigation, zoom, live drag cancellation and a separate short clip', async ({page}) => {
  await page.goto('/');
  await page.getByLabel('Song',{exact:true}).selectOption('long-song');
  await expect(page.getByRole('button',{name:'Play',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'Open timing / crop workspace',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'Song timing and cropping'});
  await expect(dialog).toBeVisible();
  expect((await dialog.boundingBox())!.width).toBeGreaterThan(1200);
  await dialog.getByLabel('Find lyrics',{exact:true}).fill('Review line 60');
  await expect(dialog.locator('.crop-lyric')).toHaveCount(1);
  await dialog.locator('.crop-lyric').click();
  await expect.poll(()=>dialog.locator('.clip-timeline__scroll').evaluate(e=>e.scrollLeft)).toBeGreaterThan(1000);
  await dialog.getByRole('button',{name:'Start here',exact:true}).click();
  await expect(dialog.getByLabel('Section start',{exact:true})).toHaveValue('2:58.00');
  await dialog.getByLabel('Section end',{exact:true}).fill('3:07.00');
  await dialog.getByLabel('Section end',{exact:true}).press('Enter');
  await dialog.getByRole('button',{name:'Fit selection',exact:true}).click();
  const original=await dialog.getByLabel('Workspace line start',{exact:true}).inputValue();
  const line=dialog.locator('.clip-timeline__line').nth(59);
  await line.scrollIntoViewIfNeeded();
  const box=(await line.boundingBox())!;
  await page.mouse.move(box.x+20,box.y+25);await page.mouse.down();
  await page.mouse.move(box.x+32,box.y+25,{steps:4});
  await expect(line).toHaveAttribute('data-dragging','valid');
  await expect(dialog.locator('.clip-timeline__drag-readout')).toContainText('Release to place');
  await page.keyboard.press('Escape');await page.mouse.up();
  await expect(dialog).toBeVisible();
  await expect(dialog.getByLabel('Workspace line start',{exact:true})).toHaveValue(original);
  await expect(dialog.locator('.clip-timeline__drag-readout')).toHaveCount(0);
  await dialog.getByLabel('New clip ID',{exact:true}).fill('long-song-short');
  await dialog.getByLabel('New clip title',{exact:true}).fill('My chorus');
  await dialog.getByRole('button',{name:'Save as new short clip',exact:true}).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByLabel('Song',{exact:true})).toHaveValue('long-song-short');
  await expect(page.getByRole('button',{name:'Play',exact:true})).toBeEnabled();
  const short=await (await page.request.get('/api/songs/long-song-short')).json();
  expect(short.song.duration).toBe(9);expect(short.review.reviewed).toBe(false);
  const originalSong=await (await page.request.get('/api/songs/long-song')).json();
  expect(originalSong.song.duration).toBe(210);
  expect(originalSong.song.lines[59].start).toBe(178);
});
